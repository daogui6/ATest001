/*
 * Article.ts - 文章数据模型接口
 * 
 * 功能说明：
 * - 定义文章数据的结构和类型
 * - 用于文章列表、详情页的数据传递
 * - 支持文章分类和原文链接
 * 
 * 数据字段说明：
 * - id: 文章唯一标识
 * - title: 文章标题
 * - desc: 文章描述/摘要
 * - author: 文章作者
 * - cid: 分类ID，用于文章分类
 * - link: 原文链接（可选）
 * - content: 文章正文内容
 */

/**
 * 文章数据模型接口
 * 
 * 表示一篇完整的文章信息，包含基本信息和内容
 * 用于前后端数据交互和本地数据存储
 */
export interface Article {
  /**
   * 文章唯一标识符
   * 用于区分不同文章，通常由后端生成
   */
  id: number;

  /**
   * 文章标题
   * 显示在文章列表和详情页的主要标题
   */
  title: string;

  /**
   * 文章描述或摘要
   * 用于文章列表页的简短介绍
   */
  desc: string;

  /**
   * 文章作者
   * 显示文章的作者信息
   */
  author: string;

  /**
   * 分类ID
   * 关联到Category接口的cid字段
   * 用于文章分类和筛选
   */
  cid: number;

  /**
   * 原文链接
   * 可选字段，指向文章的原始出处
   * 为空时表示没有外部链接
   */
  link?: string;

  /**
   * 文章正文内容
   * 文章的完整内容，可能包含HTML格式
   * 用于文章详情页展示
   */
  content: string;
}